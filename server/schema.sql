-- The users table is owned by Feature 1 and already exists. This schema only
-- adds the supporting data model; it never recreates or modifies user records.

BEGIN;

CREATE TABLE IF NOT EXISTS asset_classes (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE CHECK (
    name IN ('US Stocks', 'International Stocks', 'Bonds', 'Cash')
  ),
  target_conservative NUMERIC(5, 2) NOT NULL CHECK (
    target_conservative BETWEEN 0 AND 100
  ),
  target_moderate NUMERIC(5, 2) NOT NULL CHECK (
    target_moderate BETWEEN 0 AND 100
  ),
  target_aggressive NUMERIC(5, 2) NOT NULL CHECK (
    target_aggressive BETWEEN 0 AND 100
  )
);

INSERT INTO asset_classes (
  name,
  target_conservative,
  target_moderate,
  target_aggressive
)
VALUES
  ('US Stocks', 20.00, 35.00, 55.00),
  ('International Stocks', 10.00, 20.00, 30.00),
  ('Bonds', 55.00, 35.00, 10.00),
  ('Cash', 15.00, 10.00, 5.00)
ON CONFLICT (name) DO NOTHING;

CREATE TABLE IF NOT EXISTS assets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  asset_class_id SMALLINT NOT NULL
    REFERENCES asset_classes(id) ON DELETE RESTRICT,
  ticker TEXT NOT NULL CHECK (length(btrim(ticker)) > 0),
  name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
  quantity NUMERIC(20, 8) NOT NULL CHECK (quantity > 0),
  price NUMERIC(20, 8) NOT NULL CHECK (price >= 0),
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, id)
);

CREATE INDEX IF NOT EXISTS assets_user_created_at_idx
  ON assets (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS assets_user_asset_class_idx
  ON assets (user_id, asset_class_id);

CREATE TABLE IF NOT EXISTS stars (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  asset_id UUID NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, asset_id),
  CONSTRAINT stars_owned_asset_fkey
    FOREIGN KEY (user_id, asset_id)
    REFERENCES assets (user_id, id)
    ON DELETE CASCADE
);

COMMIT;
